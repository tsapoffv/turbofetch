package com.turbofetch.data.media

/**
 * Фильтр-граф для перекодирования видео в анимированный GIF.
 *
 * Вынесен отдельной чистой функцией, чтобы правила можно было проверить
 * тестом без устройства и без запуска ffmpeg.
 *
 * Что делает цепочка:
 *
 * 1. `scale` — кадр не шире 480 px (GIF'ы в большом разрешении весят десятки
 *    мегабайт, а в мессенджерах всё равно сжимаются).
 * 2. `select` — отбор кадров по времени: кадр пропускается, если с
 *    предыдущего выбранного прошло меньше порога. Так частота ограничивается
 *    ~15 кадрами в секунду.
 * 3. `palettegen` + `paletteuse` — два прохода: сначала строится палитра из
 *    128 цветов, потом кадры перекрашиваются по ней. GIF умеет только 256
 *    цветов, без этого картинка была бы в кашу.
 *
 * **Почему отбор по времени, а не по номеру кадра.** Раньше здесь стояло
 * `select='not(mod(n\,2))'` вместе с `setpts=N/(fps*TB)`: каждый второй кадр
 * получает метку времени 1/fps, и анимация игралась вдвое быстрее исходника
 * (длительность GIF'а была вдвое меньше). `setpts` здесь не нужен вовсе:
 * `select` и так сохраняет исходные метки времени отобранных кадров.
 *
 * **Почему порог 1/(fps + 2), а не 1/fps.** У исходника с 15 fps кадры идут
 * через 0,0667 с; при точном пороге 0,0667 часть кадров терялась бы из-за
 * округления. Запас в два кадра в секунду отсекает только настоящее
 * дублирование, а не погрешность тайминга.
 */
object GifFilter {

    /** Максимальная ширина кадра по умолчанию. */
    const val DEFAULT_WIDTH = 480

    /** Кадров в секунду в результате по умолчанию. */
    const val DEFAULT_FPS = 15

    /**
     * Порог отбора кадра: сколько секунд должно пройти с предыдущего
     * выбранного кадра.
     */
    fun threshold(fps: Int = DEFAULT_FPS): Double = 1.0 / (fps + 2)

    /**
     * Собирает фильтр-граф.
     *
     * @param width максимальная ширина кадра, пиксели
     * @param fps кадров в секунду в результате
     */
    fun build(width: Int = DEFAULT_WIDTH, fps: Int = DEFAULT_FPS): String {
        val step = threshold(fps)
        // Raw-строка: экранирование `\,` внутри выражения select должно
        // попасть в ffmpeg буквально — иначе запятая разорвёт граф фильтров.
        return """scale='min($width,iw)':-2:flags=bicubic,""" +
            """select='isnan(prev_selected_t)+gte(t-prev_selected_t\,$step)',""" +
            """split[a][b];[a]palettegen=max_colors=128[p];[b][p]paletteuse=dither=bayer"""
    }
}
